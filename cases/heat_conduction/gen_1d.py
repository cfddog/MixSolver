#!/usr/bin/env python3
# ============================================================================
# gen_1d.py -- 1D 纯导热验证算例的六面体 .cas 网格生成器（无结构求解器输入）
#
# 几何：x in [0, LX]，y in [0, LY]，z in [0, LZ]（z 方向只 1 层胞），
#       网格 NX x NY x 1，坐标单位 m（.control 里 mesh_scale = 1）。
#
# 面区（zone id / 类型，与 cases/solid_conduction 保持一致）：
#   3  Interior      内部面（y 法向 + x 法向）
#   4  symmetry (z)  z = 0 / z = LZ 两个面 -> 绝热
#   5  symmetry (y)  y = 0 / y = LY 两个面 -> 绝热
#   6  x = 0  端面   （.control 里给 bc + tbc）
#   7  x = LX 端面   （.control 里给 bc + tbc）
#
# 体区（cell zone）：
#   默认            单区 zone 2（整个棒）
#   --src           沿 x 切成 3 个**连续 id 段**体区，便于把局部体积热源挂到中间区：
#                     zone 2 : x <  s0*LX              （无热源）
#                     zone 8 : s0*LX <= x < s1*LX      （热源区）
#                     zone 9 : x >= s1*LX              （无热源）
#                   Fluent 体区记录 `(12 (id first last ...))` 只能是一个**连续
#                   id 区间**；而 cell(i,j) = 1+i+j*NX 是 i(x) 最慢、j(y) 最快，
#                   只有 NY = 1 时“x 分片”才恰好等于连续 id 段。因此 --src 要求
#                   --ny 1（否则报错），这样 zone 8 的 id 段才真的对应
#                   x in [s0*LX, s1*LX)，q_src 不会漏到区间外。
#
# 用法：
#   python3 gen_1d.py <out.cas> [NX] [--ny NY] [--src] [s0 s1]
#         NX      x 方向胞数，默认 40
#         --ny    y 方向胞数，默认 2（--src 时必须为 1）
#         --src   生成 3 体区版本；其后两个可选数字为 s0、s1（x/LX 分数，
#                 默认 0.3、0.7）
#
# 所有 Fluent 索引按十六进制输出。
# ============================================================================
import sys

LX, LY, LZ = 0.1, 0.01, 0.002      # m
NY = 2                             # y 方向层数（默认 2；--src 时为 1）

NX = 40
use_src = False
s0f, s1f = 0.3, 0.7

argv = sys.argv[1:]
if len(argv) < 1:
    raise SystemExit(__doc__ or
                     'usage: gen_1d.py <out.cas> [NX] [--ny NY] [--src] [s0 s1]')
out = argv[0]
frac = []
k = 1
while k < len(argv):
    a = argv[k]
    if a == '--src':
        use_src = True
    elif a == '--ny':
        k += 1
        if k >= len(argv):
            raise SystemExit('--ny needs a value')
        NY = int(float(argv[k]))
        if NY < 1:
            raise SystemExit('--ny must be >= 1')
    elif a.lstrip('+-').replace('.', '', 1).isdigit():
        if use_src:
            frac.append(float(a))
        else:
            NX = int(float(a))
    else:
        raise SystemExit('unknown argument: %s' % a)
    k += 1
if len(frac) >= 1:
    s0f = frac[0]
if len(frac) >= 2:
    s1f = frac[1]
if use_src and NY != 1:
    raise SystemExit('--src requires --ny 1: 体区记录只能是一个连续 id 区间，'
                     '而 x 分片只有 NY = 1 时才对应连续 id 段（见文件头说明）')

hx = lambda n: '%x' % n

NODE = (NX + 1) * (NY + 1) * 2
NCELL = NX * NY


def nid(i, j, k):
    """节点编号；i 最慢、k 最快，保证单元编号也是 i 最慢。"""
    return 1 + i + j * (NX + 1) + k * (NX + 1) * (NY + 1)


def cell(i, j):
    """单元编号：i 最慢、j 最快 -> 体区记录可以是连续 id 区间。"""
    return 1 + i + j * NX


# ---- 面数统计（z 方向 1 层，故 z 法向只有边界；对称/端面为边界）-------------
NF_YINT = (NY - 1) * NX            # y 法向内部面
NF_XINT = (NX - 1) * NY            # x 法向内部面
NF_INT = NF_YINT + NF_XINT
NF_ZSYM = 2 * NX * NY              # z = 0 / z = LZ（zone 4）
NF_YSYM = 2 * NX                   # y = 0 / y = LY（zone 5）
NF_IN = NY                         # x = 0   （zone 6）
NF_OUT = NY                        # x = LX  （zone 7）
NF = NF_INT + NF_ZSYM + NF_YSYM + NF_IN + NF_OUT

L = []
L.append('(0 "MixNSSolver 1D solid-conduction case, generated by gen_1d.py")')
L.append('')
L.append('(2 3)')                                  # 3D
L.append('(10 (0 1 %s 0 3))' % hx(NODE))
L.append('(12 (0 1 %s 0))' % hx(NCELL))
L.append('(13 (0 1 %s 0))' % hx(NF))
L.append('')

# ---- 节点 ------------------------------------------------------------------
L.append('(0 "Zone 1  Number of Nodes : %d")' % NODE)
L.append('(10 (1 1 %s 1 3)(' % hx(NODE))
for k in range(2):
    for j in range(NY + 1):
        for i in range(NX + 1):
            L.append('  %.15e   %.15e   %.15e'
                     % (i * LX / NX, j * LY / NY, k * LZ))
L.append('))')
L.append('')

# ---- 体区 ------------------------------------------------------------------
if use_src:
    ix0 = int(round(s0f * NX))
    ix1 = int(round(s1f * NX))
    if not (0 < ix0 < ix1 < NX):
        raise SystemExit('bad source range: ix0=%d ix1=%d NX=%d' % (ix0, ix1, NX))
    nz2 = ix0 * NY
    nz8 = (ix1 - ix0) * NY
    nz9 = (NX - ix1) * NY
    assert nz2 + nz8 + nz9 == NCELL
    L.append('(0 "Zone 2 %d cells 1..%d, left (no source)")' % (nz2, nz2))
    L.append('(12 (2 1 %s 1 4))' % hx(nz2))
    L.append('(45 (2 solid-left unspecified)())')
    L.append('')
    L.append('(0 "Zone 8 %d cells %d..%d, source region")'
             % (nz8, nz2 + 1, nz2 + nz8))
    L.append('(12 (8 %s %s 1 4))' % (hx(nz2 + 1), hx(nz2 + nz8)))
    L.append('(45 (8 solid-source unspecified)())')
    L.append('')
    L.append('(0 "Zone 9 %d cells %d..%d, right (no source)")'
             % (nz9, nz2 + nz8 + 1, NCELL))
    L.append('(12 (9 %s %s 1 4))' % (hx(nz2 + nz8 + 1), hx(NCELL)))
    L.append('(45 (9 solid-right unspecified)())')
    L.append('')
else:
    L.append('(0 "Zone 2 %d cells 1..%d, solid")' % (NCELL, NCELL))
    L.append('(12 (2 1 %s 1 4))' % hx(NCELL))
    L.append('(45 (2 solid unspecified)())')
    L.append('')

# ---- 面 --------------------------------------------------------------------
face_no = 0
L.append('(0 "Zone 3 %d faces %d..%d, Interior")'
         % (NF_INT, face_no + 1, face_no + NF_INT))
L.append('(13 (3 %s %s 2 4)(' % (hx(face_no + 1), hx(face_no + NF_INT)))
for i in range(NX):                                # y 法向内部面
    for j in range(NY - 1):
        L.append(' '.join(hx(v) for v in
                          (nid(i, j + 1, 0), nid(i, j + 1, 1),
                           nid(i + 1, j + 1, 1), nid(i + 1, j + 1, 0)))
                 + ' ' + hx(cell(i, j)) + ' ' + hx(cell(i, j + 1)))
face_no += NF_YINT
for j in range(NY):                                # x 法向内部面
    for i in range(NX - 1):
        L.append(' '.join(hx(v) for v in
                          (nid(i + 1, j, 0), nid(i + 1, j, 1),
                           nid(i + 1, j + 1, 1), nid(i + 1, j + 1, 0)))
                 + ' ' + hx(cell(i, j)) + ' ' + hx(cell(i + 1, j)))
face_no += NF_XINT
L.append('))')
L.append('')

L.append('(0 "Zone 4 %d faces %d..%d, Symmetry (z)")'
         % (NF_ZSYM, face_no + 1, face_no + NF_ZSYM))
L.append('(13 (4 %s %s 7 4)(' % (hx(face_no + 1), hx(face_no + NF_ZSYM)))
for k in range(2):
    for j in range(NY):
        for i in range(NX):
            L.append(' '.join(hx(v) for v in
                              (nid(i, j, k), nid(i + 1, j, k),
                               nid(i + 1, j + 1, k), nid(i, j + 1, k)))
                     + ' ' + hx(cell(i, j)) + ' 0')
face_no += NF_ZSYM
L.append('))')
L.append('')

L.append('(0 "Zone 5 %d faces %d..%d, Symmetry (y)")'
         % (NF_YSYM, face_no + 1, face_no + NF_YSYM))
L.append('(13 (5 %s %s 7 4)(' % (hx(face_no + 1), hx(face_no + NF_YSYM)))
for j in (0, NY):
    jc = 0 if j == 0 else NY - 1
    for i in range(NX):
        L.append(' '.join(hx(v) for v in
                          (nid(i, j, 0), nid(i + 1, j, 0),
                           nid(i + 1, j, 1), nid(i, j, 1)))
                 + ' ' + hx(cell(i, jc)) + ' 0')
face_no += NF_YSYM
L.append('))')
L.append('')

L.append('(0 "Zone 6 %d faces %d..%d, x = 0 end")'
         % (NF_IN, face_no + 1, face_no + NF_IN))
L.append('(13 (6 %s %s 5 4)(' % (hx(face_no + 1), hx(face_no + NF_IN)))
for j in range(NY):
    L.append(' '.join(hx(v) for v in
                      (nid(0, j, 0), nid(0, j + 1, 0),
                       nid(0, j + 1, 1), nid(0, j, 1)))
             + ' ' + hx(cell(0, j)) + ' 0')
face_no += NF_IN
L.append('))')
L.append('')

L.append('(0 "Zone 7 %d faces %d..%d, x = LX end")'
         % (NF_OUT, face_no + 1, face_no + NF_OUT))
L.append('(13 (7 %s %s 4 4)(' % (hx(face_no + 1), hx(face_no + NF_OUT)))
for j in range(NY):
    L.append(' '.join(hx(v) for v in
                      (nid(NX, j, 0), nid(NX, j + 1, 0),
                       nid(NX, j + 1, 1), nid(NX, j, 1)))
             + ' ' + hx(cell(NX - 1, j)) + ' 0')
face_no += NF_OUT
L.append('))')
L.append('')

assert face_no == NF, (face_no, NF)

with open(out, 'w') as f:
    f.write('\n'.join(L) + '\n')

tag = 'src (3 cell zones)' if use_src else 'single cell zone'
print('wrote %s : %d cells, %d faces, %s, NX = %d'
      % (out, NCELL, NF, tag, NX))
if use_src:
    print('  zone 2 : cells 1..%-4d (x <  %.6g m)' % (nz2, s0f * LX))
    print('  zone 8 : cells %d..%-4d(%.6g <= x < %.6g m)   <- 体热源 q_src'
          % (nz2 + 1, nz2 + nz8, s0f * LX, s1f * LX))
    print('  zone 9 : cells %d..%-4d(x >= %.6g m)'
          % (nz2 + nz8 + 1, NCELL, s1f * LX))
